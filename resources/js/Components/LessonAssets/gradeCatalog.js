export function getGradeCatalog(gradeLevel = 4) {
    const grade = Math.min(9, Math.max(4, Number(gradeLevel) || 4));
    return { grade, ...GRADE_CATALOG[grade] };
}

export function gradeBand(gradeLevel = 1) {
    const grade = Math.min(9, Math.max(1, Number(gradeLevel) || 1));
    if (grade <= 3) return 'foundation';
    if (grade <= 6) return 'intermediate';
    return 'advanced';
}

export function withIds(items = []) {
    return items.map((item) => ({ id: uid('item'), ...item }));
}

export default GRADE_CATALOG;
